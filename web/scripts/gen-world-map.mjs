// Dev-only: regenerates src/assets/world-map.ts (not run in CI).
//   mkdir /tmp/geo && cd /tmp/geo && npm init -y && npm i world-atlas topojson-client d3-geo
//   node web/scripts/gen-world-map.mjs /tmp/geo
// The panel draws the map from the committed asset and projects node
// positions with the same Natural Earth 1 formula (naturalEarth1Raw in
// src/nodeGeo.ts); this script checks that both agree with d3.
import { createRequire } from 'node:module'
import { readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'

const dir = resolve(process.argv[2] || '.')
const req = createRequire(join(dir, 'package.json'))
const { feature } = req('topojson-client')
const { geoNaturalEarth1, geoPath } = req('d3-geo')
const topo = JSON.parse(readFileSync(join(dir, 'node_modules/world-atlas/countries-110m.json'), 'utf8'))

const W = 1000
const all = feature(topo, topo.objects.countries).features
const land = all.filter((f) => f.id !== '010') // crop Antarctica

// Fit the width to the sphere, then crop the height to the land that is left.
const proj = geoNaturalEarth1().fitWidth(W, { type: 'Sphere' })
const bounds = geoPath(proj).bounds({ type: 'FeatureCollection', features: land })
const pad = 6
const top = Math.floor(bounds[0][1]) - pad
const H = Math.ceil(bounds[1][1]) + pad - top
const scale = +proj.scale().toFixed(3)
const tx = +proj.translate()[0].toFixed(3)
const ty = +(proj.translate()[1] - top).toFixed(3)
proj.scale(scale).translate([tx, ty])

const path = geoPath(proj).digits(1)
const countries = {}
for (const f of land) {
  const d = path(f)
  if (d) countries[String(+f.id)] = d
}

// Same formula as src/nodeGeo.ts.
function raw(l, p) {
  const p2 = p * p, p4 = p2 * p2
  return [l * (0.8707 - 0.131979 * p2 + p4 * (-0.013791 + p4 * (0.003971 * p2 - 0.001529 * p4))),
    p * (1.007226 + p2 * (0.015085 + p4 * (-0.044475 + 0.028874 * p2 - 0.005916 * p4)))]
}
const mine = (lng, lat) => {
  const [x, y] = raw((lng * Math.PI) / 180, (lat * Math.PI) / 180)
  return [scale * x + tx, ty - scale * y]
}
const cities = { Tokyo: [139.69, 35.69], London: [-0.13, 51.5], 'Los Angeles': [-118.24, 34.05], Sydney: [151.2, -33.87], 'Sao Paulo': [-46.63, -23.55], Singapore: [103.82, 1.35] }
for (const [n, [lng, lat]] of Object.entries(cities)) {
  const a = proj([lng, lat])
  const b = mine(lng, lat)
  if (Math.hypot(a[0] - b[0], a[1] - b[1]) > 0.01) throw new Error(`projection mismatch for ${n}: ${a} vs ${b}`)
}

const body = Object.entries(countries).map(([k, v]) => `  ${k}: '${v}',`).join('\n')
const out = `// Generated by scripts/gen-world-map.mjs from world-atlas countries-110m
// (Natural Earth 1 projection). Do not edit by hand.
export const MAP_W = ${W}
export const MAP_H = ${H}
export const MAP_SCALE = ${scale}
export const MAP_TX = ${tx}
export const MAP_TY = ${ty}

// Country outlines keyed by ISO 3166-1 numeric code.
export const COUNTRY_PATHS: Record<number, string> = {
${body}
}
`
writeFileSync(new URL('../src/assets/world-map.ts', import.meta.url), out)
console.log(`viewBox ${W}x${H}, scale ${scale}, translate ${tx},${ty}, ${Object.keys(countries).length} countries, ${(out.length / 1024).toFixed(1)} KB`)
